// Helper function to evaluate removeduplicates for problem constraints.
function removeDuplicates(nums) {
    if (nums.length === 0) return 0;
    let k = 1;
    for (let i = 1; i < nums.length; i++) {
        if (nums[i] !== nums[i - 1]) {
            nums[k++] = nums[i];
        }
    }
    return k;
}

module.exports = { removeDuplicates };