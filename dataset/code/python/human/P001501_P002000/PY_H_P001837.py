missing = []
found = []
for title in titles:
    rec = by_title.get(title.lower())
    if rec:
        found.append(rec)
    else:
        missing.append(title)

print("FOUND", len(found), "MISSING", len(missing))
for title in missing:
    print("MISSING:", title)
    lowered = title.lower()
    cands = [
        rec
        for rec in by_id.values()
        if lowered.replace(" ", "-") in rec["slug"] or lowered in rec["title"].lower()
    ]
    for cand in cands[:8]:
        print("  cand", cand)

