import sys
sys.setrecursionlimit(500000)

class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right

def build_tree(nodes):
    if not nodes:
        return None
    root = TreeNode(nodes[0])
    queue = [root]
    i = 1
    while queue and i < len(nodes):
        node = queue.pop(0)
        if i < len(nodes) and nodes[i] is not None:
            node.left = TreeNode(nodes[i])
            queue.append(node.left)
        i += 1
        if i < len(nodes) and nodes[i] is not None:
            node.right = TreeNode(nodes[i])
            queue.append(node.right)
        i += 1
    return root

def count_pseudo_palindromic_paths(node, mask):
    if not node:
        return 0
    mask ^= (1 << node.val)
    if not node.left and not node.right:
        # Check if mask has at most 1 bit set
        if mask & (mask - 1) == 0:
            return 1
        return 0
    return count_pseudo_palindromic_paths(node.left, mask) + count_pseudo_palindromic_paths(node.right, mask)

def solve():
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    idx = 0
    n = int(input_data[idx]); idx += 1
    vals = []
    for _ in range(n):
        v = int(input_data[idx]); idx += 1
        vals.append(v if v != -1 else None)
        
    root = build_tree(vals)
    print(count_pseudo_palindromic_paths(root, 0))

solve()

