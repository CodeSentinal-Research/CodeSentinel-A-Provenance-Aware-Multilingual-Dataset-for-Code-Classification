
from typing import List

class Solution:
    def bubbleSort(self, arr: List[int]) -> List[int]:
        n = len(arr)
        for i in range(n - 1):
            for j in range(n - i - 1):
                if arr[j] > arr[j + 1]:
                    arr[j], arr[j + 1] = arr[j + 1], arr[j]
        return arr
