"""
Unit and Smoke Tests for the Research Pipeline.
Verifies:
1. Hash computation and normalization
2. Leakage-free split partitioning
3. Evaluation metric calculations
4. Model smoke execution
"""

import unittest
from pathlib import Path
import numpy as np

from src.data.ingestion import compute_hashes
from src.data.splitter import DisjointSetUnion, generate_splits
from src.evaluation.metrics import evaluate_predictions
from src.models.tfidf_svm import TfidfSvmModel
from src.models.tfidf_rf import TfidfRfModel

class TestResearchPipeline(unittest.TestCase):

    def test_hash_normalization(self):
        c_code1 = "int main() {\n    return 0;\n}"
        c_code2 = "int main() {   return 0;  }"
        raw1, norm1 = compute_hashes(c_code1)
        raw2, norm2 = compute_hashes(c_code2)

        self.assertNotEqual(raw1, raw2, "Raw hashes should differ with different whitespace")
        self.assertEqual(norm1, norm2, "Normalized hashes should match after whitespace normalization")

    def test_dsu_clustering(self):
        dsu = DisjointSetUnion()
        dsu.union("sample_1", "problem_P001")
        dsu.union("sample_2", "problem_P001")
        dsu.union("sample_3", "problem_P002")

        self.assertEqual(dsu.find("sample_1"), dsu.find("sample_2"))
        self.assertNotEqual(dsu.find("sample_1"), dsu.find("sample_3"))

    def test_leakage_free_split_generation(self):
        dummy_samples = [
            {"sample_id": f"s_{i}", "label": i % 2, "generator": "chatgpt" if i % 2 else "human",
             "language": "python", "norm_sha256": f"norm_{i//2}", "problem_id": f"P00{i//3}", "code": f"x = {i}"}
            for i in range(30)
        ]

        train, val, test, audit = generate_splits(dummy_samples, output_dir=Path("outputs/test_splits"))

        train_ids = {s["sample_id"] for s in train}
        val_ids = {s["sample_id"] for s in val}
        test_ids = {s["sample_id"] for s in test}

        self.assertEqual(len(train_ids.intersection(val_ids)), 0)
        self.assertEqual(len(train_ids.intersection(test_ids)), 0)
        self.assertEqual(len(val_ids.intersection(test_ids)), 0)

        # Check hash leak
        train_h = {s["norm_sha256"] for s in train}
        val_h = {s["norm_sha256"] for s in val}
        test_h = {s["norm_sha256"] for s in test}

        self.assertEqual(len(train_h.intersection(val_h)), 0)
        self.assertEqual(len(train_h.intersection(test_h)), 0)
        self.assertEqual(len(val_h.intersection(test_h)), 0)

    def test_metrics_evaluation(self):
        y_true = [0, 0, 1, 1, 1]
        y_pred = [0, 1, 1, 1, 0]
        y_prob = [0.1, 0.8, 0.9, 0.7, 0.4]

        metrics = evaluate_predictions(y_true, y_pred, y_prob, model_name="unit_test_model", save_dir=Path("outputs/test_metrics"))
        self.assertIn("accuracy", metrics)
        self.assertIn("macro_f1", metrics)
        self.assertIn("roc_auc", metrics)
        self.assertEqual(metrics["sample_counts"]["total"], 5)

    def test_tfidf_svm_smoke(self):
        texts = [
            "def add(a, b): return a + b",
            "int main() { printf(\"hello\"); return 0; }",
            "class Solution { public int solve() { return 1; } }",
            "console.log('generated by ai');"
        ]
        labels = [0, 0, 1, 1]

        model = TfidfSvmModel()
        duration = model.fit(texts, labels)
        self.assertGreater(duration, 0)
        preds, probs, _ = model.predict(texts)
        self.assertEqual(len(preds), 4)
        self.assertEqual(len(probs), 4)

    def test_cooldown_manager(self):
        from src.utils.cooldown import CooldownManager
        import time
        mgr = CooldownManager(interval_seconds=0.05, cooldown_seconds=0.01, component_name="Test")
        mgr.check("Immediate check (should not pause)")
        self.assertEqual(mgr.pause_count, 0)
        time.sleep(0.06)
        mgr.check("Elapsed check (should pause)")
        self.assertEqual(mgr.pause_count, 1)
        self.assertGreater(mgr.total_paused_seconds, 0)

if __name__ == "__main__":
    unittest.main()

